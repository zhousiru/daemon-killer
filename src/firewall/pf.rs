//! Policy -> pf anchor text, plus edits of the live main ruleset. Pure; `pfctl` is called
//! from `platform::macos::pf`.
#![cfg_attr(not(target_os = "macos"), allow(dead_code))]

use crate::policy::{Policy, Rule};
use ipnet::IpNet;
use std::fmt::Write as _;

pub const ANCHOR: &str = "daemon-killer";
pub const BLOCK_RULE: &str = "block drop quick all";

fn join(nets: &[IpNet]) -> String {
    nets.iter()
        .map(ToString::to_string)
        .collect::<Vec<_>>()
        .join(", ")
}

/// The anchor ruleset. An open policy is an empty anchor.
pub fn compile(p: &Policy) -> String {
    if !p.blocking {
        return String::new();
    }
    let mut tables = String::new();
    let mut body = String::new();
    for rule in &p.rules {
        match rule {
            Rule::Loopback => body.push_str("pass quick on lo0 all\n"),
            Rule::Interface(i) => {
                let _ = writeln!(body, "pass quick on {i} all keep state");
            }
            Rule::Core { to: None } => {
                let _ = writeln!(
                    body,
                    "pass out quick proto {{ tcp, udp }} user {} keep state",
                    p.core.uid
                );
            }
            Rule::Core { to: Some(nets) } => {
                if !nets.is_empty() {
                    let _ = writeln!(tables, "table <dk_upstream> const {{ {} }}", join(nets));
                    let _ = writeln!(
                        body,
                        "pass out quick proto {{ tcp, udp }} to <dk_upstream> user {} keep state",
                        p.core.uid
                    );
                }
            }
            // Rejected by config validation; pf cannot match executables.
            Rule::Program(path) => {
                let _ = writeln!(body, "# not supported by pf: program {}", path.display());
            }
            Rule::Networks(nets) => {
                let _ = writeln!(tables, "table <dk_allow> const {{ {} }}", join(nets));
                body.push_str("pass out quick to <dk_allow> keep state\n");
                body.push_str("pass in quick from <dk_allow> keep state\n");
            }
            Rule::Dhcp => body.push_str(concat!(
                "pass out quick inet proto udp from any port 68 to any port 67 user 0 keep state\n",
                "pass in quick inet proto udp from any port 67 to any port 68\n",
                "pass out quick inet6 proto udp from any port 546 to any port 547 user 0 keep state\n",
                "pass in quick inet6 proto udp from any port 547 to any port 546\n",
                "pass quick inet6 proto icmp6 icmp6-type { routersol, routeradv, neighbrsol, neighbradv }\n",
            )),
        }
    }
    format!(
        "# Generated by daemon-killer. Do not edit.\n\
         # Fail-closed: anything not passed below is dropped.\n\
         {tables}{body}{BLOCK_RULE}\n"
    )
}

/// Insert our reference before all live filter rules, preserving normalization.
/// NAT/rdr/dummynet rules are not reloaded by `-R`.
pub fn main_ruleset(conf: &str) -> String {
    let original = without_our_anchor(conf);
    let mut lines: Vec<&str> = original.lines().collect();
    let first = lines
        .iter()
        .position(|line| first_filter_rule(line).is_some())
        .unwrap_or(lines.len());
    let ours = format!("anchor \"{ANCHOR}\" all");
    lines.insert(first, &ours);
    lines.join("\n") + "\n"
}

pub fn without_our_anchor(conf: &str) -> String {
    let quoted = format!("\"{ANCHOR}\"");
    conf.lines()
        .filter(|line| {
            let mut words = line.split_whitespace();
            !(words.next() == Some("anchor") && words.next() == Some(quoted.as_str()))
        })
        .map(|line| format!("{line}\n"))
        .collect()
}

pub fn first_filter_rule(rules: &str) -> Option<&str> {
    const NON_FILTER: &[&str] = &[
        "scrub", "nat", "rdr", "binat", "dummynet", "set ", "table ", "altq", "queue", "No ALTQ",
        "ALTQ",
    ];
    rules
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .find(|l| !NON_FILTER.iter().any(|p| l.starts_with(p)))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{Config, Egress};

    fn cfg() -> Config {
        Config {
            tun_device: "utun1500".into(),
            allow_lan: false,
            allow_dhcp: false,
            ..Config::default()
        }
    }

    #[test]
    fn strict_minimal_rules() {
        let ups = ["1.2.3.4/32".parse().unwrap()];
        let r = compile(&Policy::build(&cfg(), &ups));
        let body: Vec<&str> = r.lines().filter(|l| !l.starts_with('#')).collect();
        assert_eq!(
            body,
            [
                "table <dk_upstream> const { 1.2.3.4/32 }",
                "pass quick on lo0 all",
                "pass quick on utun1500 all keep state",
                "pass out quick proto { tcp, udp } to <dk_upstream> user 0 keep state",
                "block drop quick all",
            ]
        );
    }

    #[test]
    fn block_rule_is_last_and_core_rule_has_no_address_bypass() {
        let c = Config {
            egress: Egress::Core,
            ..cfg()
        };
        let r = compile(&Policy::build(&c, &["1.2.3.4/32".parse().unwrap()]));
        assert_eq!(r.lines().last(), Some(BLOCK_RULE));
        assert!(r.contains("pass out quick proto { tcp, udp } user 0 keep state"));
        assert!(!r.contains("dk_upstream"));
        assert!(!r.contains("dk_allow"));
    }

    #[test]
    fn open_policy_is_an_empty_anchor() {
        assert_eq!(compile(&Policy::open()), "");
    }

    #[test]
    fn anchor_goes_before_first_filter_anchor() {
        let conf = "scrub-anchor \"com.apple/*\"\nnat-anchor \"com.apple/*\"\nrdr-anchor \"com.apple/*\"\ndummynet-anchor \"com.apple/*\"\nanchor \"com.apple/*\"\nload anchor \"com.apple\" from \"/etc/pf.anchors/com.apple\"\n";
        let out = main_ruleset(conf);
        let lines: Vec<&str> = out.lines().collect();
        assert_eq!(lines[4], "anchor \"daemon-killer\" all");
        assert_eq!(lines[5], "anchor \"com.apple/*\"");
        assert_eq!(main_ruleset("").trim(), "anchor \"daemon-killer\" all");
    }

    #[test]
    fn live_main_preserves_dynamic_rules_and_moves_only_our_anchor() {
        let before = "scrub-anchor \"com.apple/*\" all fragment reassemble\npass in quick on lo0 all\nanchor \"com.apple.internet-sharing\" all\nanchor \"daemon-killer\" all\n";
        let after = main_ruleset(before);
        assert_eq!(
            first_filter_rule(&after),
            Some("anchor \"daemon-killer\" all")
        );
        assert_eq!(after.matches("anchor \"daemon-killer\"").count(), 1);
        assert_eq!(without_our_anchor(&after), without_our_anchor(before));
        assert_eq!(main_ruleset(&after), after);
    }

    #[test]
    fn first_filter_rule_skips_translation() {
        let main = "No ALTQ support in kernel\nscrub-anchor \"com.apple/*\" all fragment reassemble\nanchor \"daemon-killer\" all\nanchor \"com.apple/*\" all\n";
        assert_eq!(
            first_filter_rule(main),
            Some("anchor \"daemon-killer\" all")
        );
    }
}
